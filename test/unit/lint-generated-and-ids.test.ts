import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { lintVault } from "../../src/core/lint.js";

// Exact headers from src/core/index-regen.ts renderIndex and src/core/log.ts HEADER.
const INDEX_HEADER = `# Research Index\n\n> Auto-generated by semantic-sidekick. Changes are overwritten on apply_patch. Add prose to per-note files, not here.\n\n- [Foo](foo)\n`;
const LOG_HEADER = `# Vault Log\n\n> Append-only session and ingest log. Machine-readable YAML blocks follow each line.\n\n`;

let dir: string;
async function seed(rel: string, content: string) {
  await mkdir(join(dir, rel, ".."), { recursive: true });
  await writeFile(join(dir, rel), content, "utf-8");
}
const note = (extra = "") => `---\ntitle: N\ntype: note\nstatus: active\nsources: [x]\n${extra}---\nbody`;

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "lint-gen-"));
});
afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

describe("#35 generated files skip schema validation", () => {
  it("a generated folder INDEX.md and root log.md give no schema_violations", async () => {
    await seed("research/INDEX.md", INDEX_HEADER);
    await seed("log.md", LOG_HEADER);
    const r = await lintVault(dir);
    expect(r.byRule.schema_violations).toEqual([]);
  });

  it("guard: a hand-written frontmatter-less note still gets schema_violations", async () => {
    await seed("notes/foo.md", "# Foo\n\njust prose\n");
    const r = await lintVault(dir);
    expect(r.byRule.schema_violations.some((f) => f.path === "notes/foo.md")).toBe(true);
  });

  it("guard: an INDEX.md without the generated banner is still linted", async () => {
    await seed("notes/INDEX.md", "# My own index\n\nhand written\n");
    const r = await lintVault(dir);
    expect(r.byRule.schema_violations.length).toBeGreaterThan(0);
  });
});

describe("#35 edge cases", () => {
  it("a generated file with hand-added frontmatter is linted normally", async () => {
    await seed("research/INDEX.md", `---\ntitle: X\n---\n` + INDEX_HEADER);
    const r = await lintVault(dir);
    expect(r.byRule.schema_violations.length).toBeGreaterThan(0);
  });

  it("CRLF line endings in the generated header are still recognised", async () => {
    await seed("research/INDEX.md", INDEX_HEADER.replace(/\n/g, "\r\n"));
    const r = await lintVault(dir);
    expect(r.byRule.schema_violations).toEqual([]);
  });
});

describe("#27 wikilinks resolve folder-form incidents", () => {
  const links = (slug: string) => seed("notes/a.md", note().replace("body", `see [[${slug}]]`));
  const broken = async (slug: string) => {
    const r = await lintVault(dir, { pathGlob: "notes/a.md" });
    return r.byRule.broken_links.some((f) => f.message.includes(slug));
  };

  it("resolves by incident folder slug (narrative.md)", async () => {
    await seed("incidents/2026-07-09-slug/narrative.md", note());
    await links("2026-07-09-slug");
    expect(await broken("2026-07-09-slug")).toBe(false);
  });

  it("resolves by frontmatter id", async () => {
    await seed("incidents/x/narrative.md", note("id: 2026-07-09-slug\n"));
    await links("2026-07-09-slug");
    expect(await broken("2026-07-09-slug")).toBe(false);
  });

  it("resolves by frontmatter incident_id", async () => {
    await seed("incidents/x/facts.md", note("incident_id: 2026-07-09-slug\n"));
    await links("2026-07-09-slug");
    expect(await broken("2026-07-09-slug")).toBe(false);
  });

  it("guard: a truly missing target is still reported", async () => {
    await links("2026-07-09-slug");
    expect(await broken("2026-07-09-slug")).toBe(true);
  });

  it("resolves [[slug#heading]] and [[slug|alias]]", async () => {
    await seed("incidents/2026-07-09-slug/narrative.md", note());
    await seed("notes/a.md", note().replace("body", "see [[2026-07-09-slug#Impact]] and [[2026-07-09-slug|the incident]]"));
    expect(await broken("2026-07-09-slug")).toBe(false);
  });

  it("a folder with narrative.md and facts.md resolves", async () => {
    await seed("incidents/s1/narrative.md", note());
    await seed("incidents/s1/facts.md", note());
    await links("s1");
    expect(await broken("s1")).toBe(false);
  });

  it("a non-string id is ignored, not thrown", async () => {
    await seed("incidents/x/narrative.md", note("id: 42\nincident_id: [a, b]\n"));
    await links("42");
    expect(await broken("42")).toBe(true);
  });

  it("an unreadable note does not abort the lint; an empty vault is clean", async () => {
    expect((await lintVault(dir)).byRule.broken_links).toEqual([]);
    await mkdir(join(dir, "dir.md"), { recursive: true }); // glob match that readFile rejects
    await seed("notes/a.md", note());
    await expect(lintVault(dir)).resolves.toBeDefined();
  });
});
